<?php

declare(strict_types=1);

/*
 * Prints the strings the Twig templates translate as PHP calls, for wp i18n make-pot, which reads no Twig. A note
 * for translators is a Twig comment on the line before the call, or before it on its line:
 *
 *   {# translators: %s: product name -#}
 *
 *   php bin/twig-strings.php templates > var/i18n/templates.php
 */

$root = $argv[1] ?? throw new InvalidArgumentException('Usage: php bin/twig-strings.php <templates folder>');
$literal = '(\'(?:[^\'\\\\]|\\\\.)*\'|"(?:[^"\\\\]|\\\\.)*")';
$call = '/\b(__|_n)\(\s*' . $literal . '(?:\s*,\s*' . $literal . ')?/';

echo "<?php\n\n// Generated by bin/twig-strings.php from the Twig templates; not loaded by the plugin.\n";
$files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS));
$paths = [];
foreach ($files as $file) {
    if ($file->isFile() && str_ends_with($file->getFilename(), '.twig')) {
        $paths[] = $file->getPathname();
    }
}
sort($paths);
foreach ($paths as $path) {
    $previous = '';
    foreach (file($path) ?: [] as $line) {
        if (preg_match_all($call, $line, $matches, PREG_SET_ORDER) > 0) {
            $note = preg_match('/\{#-?\s*(translators:.*?)\s*-?#\}/', $previous . $line, $found) === 1 ? str_replace('*/', '* /', $found[1]) : null;
            foreach ($matches as $match) {
                // The note is about the placeholders, so it goes with every string on the line that has some.
                if ($note !== null && str_contains($match[2] . ($match[3] ?? ''), '%')) {
                    printf("/* %s */\n", $note);
                }
                // Twig and PHP read these quoted strings alike.
                $arguments = $match[1] === '_n' ? $match[2] . ', ' . $match[3] . ', 1' : $match[2];
                printf("%s(%s, 'orillacart');\n", $match[1], $arguments);
            }
        }
        $previous = $line;
    }
}
