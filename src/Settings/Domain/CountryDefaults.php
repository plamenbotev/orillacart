    /** Countries that weigh in pounds and measure in inches. */
    private const array IMPERIAL = ['US', 'LR', 'MM'];

    /** @return array{currency: string, position: CurrencyPosition, sign: string}|null */
    public static function money(string $country): ?array
    {
        $money = self::MONEY[$country] ?? null;

        return $money === null ? null : ['currency' => $money[0], 'position' => CurrencyPosition::from($money[1]), 'sign' => $money[2]];
    }

    public static function weightUnit(string $country): WeightUnit
    {
        return \in_array($country, self::IMPERIAL, true) ? WeightUnit::Pound : WeightUnit::Kilogram;
    }

    public static function dimensionUnit(string $country): DimensionUnit
    {
        return \in_array($country, self::IMPERIAL, true) ? DimensionUnit::Inch : DimensionUnit::Centimetre;
    }
